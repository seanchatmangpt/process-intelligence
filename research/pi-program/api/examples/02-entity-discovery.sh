#!/bin/bash
# Example 2: Entity Discovery & Provenance Tracing
# Purpose: List entities and trace their provenance to source law
# Authority: Process Intelligence Research Directorate

set -e

API_BASE="https://api.process-intelligence.research/v1"
API_KEY="${PI_API_KEY}"

if [ -z "$API_KEY" ]; then
  echo "Error: PI_API_KEY environment variable not set"
  exit 1
fi

echo "=== Entity Discovery & Provenance Tracing ==="
echo

# List all artifacts
echo "1. Listing all artifacts..."
ENTITIES=$(curl -s "$API_BASE/entities/Artifact?limit=5" \
  -H "X-API-Key: $API_KEY")

ARTIFACT_COUNT=$(echo "$ENTITIES" | jq '.total')
echo "Total artifacts in ecosystem: $ARTIFACT_COUNT"
echo

# Get details for first artifact
FIRST_ARTIFACT=$(echo "$ENTITIES" | jq '.entities[0]')
ARTIFACT_ID=$(echo "$FIRST_ARTIFACT" | jq -r '.id')
ARTIFACT_NAME=$(echo "$FIRST_ARTIFACT" | jq -r '.name')

echo "2. Getting details for artifact: $ARTIFACT_NAME"
ARTIFACT_DETAILS=$(curl -s "$API_BASE/entity/$ARTIFACT_ID" \
  -H "X-API-Key: $API_KEY")

echo "Artifact ID: $ARTIFACT_ID"
echo "Created: $(echo "$ARTIFACT_DETAILS" | jq -r '.created_at')"
echo "Content Hash: $(echo "$ARTIFACT_DETAILS" | jq -r '.content_hash')"
echo

# Trace provenance
echo "3. Tracing provenance for: $ARTIFACT_NAME"
PROVENANCE=$(curl -s "$API_BASE/provenance/$ARTIFACT_ID" \
  -H "X-API-Key: $API_KEY")

echo "Generated by rule: $(echo "$PROVENANCE" | jq -r '.generated_by')"
echo "Rule name: $(echo "$PROVENANCE" | jq -r '.rule_definition.rule_name')"
echo

echo "Sourced from:"
echo "$PROVENANCE" | jq '.sourced_from[] | {source_type, source_id, claim}' | head -20
echo

# Get authorization checkpoint
echo "4. Authorization:"
echo "$PROVENANCE" | jq '.authorization'
echo

# Verify receipts
echo "5. Verifying cryptographic receipt chain..."
RECEIPT_ID=$(echo "$ARTIFACT_DETAILS" | jq -r '.receipts[0].receipt_id')

RECEIPT=$(curl -s "$API_BASE/receipt/$RECEIPT_ID" \
  -H "X-API-Key: $API_KEY")

echo "Receipt ID: $(echo "$RECEIPT" | jq -r '.receipt_id')"
echo "Verified: $(echo "$RECEIPT" | jq -r '.verified')"
echo "Issued At: $(echo "$RECEIPT" | jq -r '.issued_at')"

if [ "$(echo "$RECEIPT" | jq -r '.chain_next')" != "null" ]; then
  echo "Next in chain: $(echo "$RECEIPT" | jq -r '.chain_next')"
fi

echo
echo "✓ Provenance trace complete"
