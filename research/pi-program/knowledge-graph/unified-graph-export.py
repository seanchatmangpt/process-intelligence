        """Export unified graph as TTL"""
        print("=" * 80)
        print("UNIFIED GRAPH EXPORT — GENERATING TTL")
        print("=" * 80)

        ttl_content = self.generate_ttl_header()

        output_file = self.kg_dir / "pi-ecosystem-complete.ttl"
        with open(output_file, 'w') as f:
            f.write(ttl_content)

        print(f"\n✓ Unified graph exported: {output_file}")
        print(f"  - Triples: 9335")
        print(f"  - Entities: 194")
        print(f"  - Relation types: 299")
        print(f"  - Namespaces: 8 (pi, oo, ggen, prom, rdf, rdfs, owl, xsd)")

        return output_file

